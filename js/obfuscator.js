function randomVarName(length = 8) {
  const chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
  let result = "_";
  for (let i = 0; i < length; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

export function protectLuauScript(rawCode, { obfuscate = true, envCheck = true } = {}) {
  let finalCode = rawCode;

  if (envCheck) {
    finalCode = `if not game or not game:GetService("Players") then return end\n` + finalCode;
  }

  if (!obfuscate) return `-- Generated by DarkAI\n` + finalCode;

  const keyBytes = Array.from({ length: 16 }, () => Math.floor(Math.random() * 250) + 1);
  const payloadBytes = new TextEncoder().encode(finalCode);
  const encrypted = Array.from(payloadBytes, (b, i) => b ^ keyBytes[i % keyBytes.length]);

  const vKey = randomVarName();
  const vData = randomVarName();
  const vOut = randomVarName();
  const vFunc = randomVarName();

  return `-- Protected by DarkAI
local ${vKey} = {${keyBytes.join(",")}}
local ${vData} = {${encrypted.join(",")}}
local ${vOut} = table.create(#${vData})
for i = 1, #${vData} do
    local k = ${vKey}[((i - 1) % #${vKey}) + 1]
    ${vOut}[i] = string.char(bit32.bxor(${vData}[i], k))
end
local ${vFunc} = loadstring(table.concat(${vOut}))
if ${vFunc} then
    task.spawn(${vFunc})
end`;
}
